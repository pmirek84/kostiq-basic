const fs = require('fs');
const path = require('path');
const { compile } = require('json-schema-to-typescript');

const CONTRACTS_CONFIG = [
  {
    schemaRelPath: 'shared/contracts/timeEntry.schema.json',
    outputRelPath: 'shared/contracts/timeEntry.generated.ts',
    rootTitle: 'TimeEntryRoot'
  },
  {
    schemaRelPath: 'shared/contracts/job.schema.json',
    outputRelPath: 'shared/contracts/job.generated.ts',
    rootTitle: 'JobRoot'
  },
  {
    schemaRelPath: 'shared/contracts/offer.schema.json',
    outputRelPath: 'shared/contracts/offer.generated.ts',
    rootTitle: 'OfferRoot'
  },
  {
    schemaRelPath: 'shared/contracts/invoice.schema.json',
    outputRelPath: 'shared/contracts/invoice.generated.ts',
    rootTitle: 'InvoiceRoot'
  }
];

async function generate() {
  const isCheck = process.argv.includes('--check');
  const rootDir = path.resolve(__dirname, '..');

  for (const config of CONTRACTS_CONFIG) {
    const schemaPath = path.join(rootDir, config.schemaRelPath);
    const outputPath = path.join(rootDir, config.outputRelPath);

    if (!fs.existsSync(schemaPath)) {
      console.error(`[CONTRACTS ERROR] Schema file ${schemaPath} not found.`);
      process.exit(1);
    }

    const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));

    const rootProperties = {};
    for (const defName of Object.keys(schema.definitions || {})) {
      rootProperties[defName] = { $ref: `#/definitions/${defName}` };
    }

    const combinedSchema = {
      ...schema,
      title: config.rootTitle,
      type: 'object',
      properties: rootProperties
    };

    const ts = await compile(combinedSchema, config.rootTitle, {
      bannerComment: `/* eslint-disable */\n/**\n * This file was automatically generated by json-schema-to-typescript.\n * DO NOT MODIFY IT BY HAND. Instead, modify ${path.basename(schemaPath)} and run npm run generate:contracts.\n */\n`,
      style: {
        singleQuote: true
      }
    });

    if (isCheck) {
      if (!fs.existsSync(outputPath)) {
        console.error(`[CONTRACTS CHECK FAILED] Output file ${outputPath} does not exist. Run "npm run generate:contracts".`);
        process.exit(1);
      }
      const currentTs = fs.readFileSync(outputPath, 'utf8');
      const normCurrent = currentTs.replace(/\r\n/g, '\n').trim();
      const normGenerated = ts.replace(/\r\n/g, '\n').trim();

      if (normCurrent !== normGenerated) {
        console.error(`[CONTRACTS CHECK FAILED] ${config.outputRelPath} is out of sync with ${config.schemaRelPath}.`);
        console.error('Please run: npm run generate:contracts');
        process.exit(1);
      }
    } else {
      fs.writeFileSync(outputPath, ts, 'utf8');
      console.log(`[CONTRACTS] Successfully compiled ${path.basename(schemaPath)} -> ${path.basename(outputPath)}`);
    }
  }

  if (isCheck) {
    console.log('[CONTRACTS CHECK PASSED] Generated contracts are strictly up to date.');
  }
}

generate().catch(err => {
  console.error('[CONTRACTS ERROR]:', err);
  process.exit(1);
});
